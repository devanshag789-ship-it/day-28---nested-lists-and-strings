# Day 28: Nested lists and string concatenation

nested_list = [
    ["hello", "world"],
    ["hello", "world"],
    ["hello", "world"]
]

print("Nested list:", nested_list)
print("First inner list:", nested_list[0])
print("First word of first inner list:", nested_list[0][0])

message = "hello " + "world"
print("Joined string:", message)
